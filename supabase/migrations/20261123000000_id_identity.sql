-- id columns had no default, so every insert without an explicit id failed.
-- Make them auto-increment and start after the largest existing id.
do $$
declare
  t text;
begin
  foreach t in array array[
    'roll', 'urituse_liik', 'osalusroll', 'eelarve', 'liige',
    'juhatuseliikmesus', 'uritus', 'osalus', 'kulu'
  ] loop
    if exists (
      select 1 from pg_attribute a
      where a.attrelid = ('public.' || t)::regclass and a.attname = 'id'
        and a.attidentity = '' and not a.atthasdef
    ) then
      execute format('alter table public.%I alter column id add generated by default as identity', t);
    end if;
    -- next id = largest id + 1 (1 for an empty table)
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce(max(id), 0) + 1, false) from public.%I',
      'public.' || t, t
    );
  end loop;
end $$;
